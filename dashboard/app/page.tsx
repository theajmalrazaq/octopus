'use client';

import { useMemo, useState } from 'react';

type Gender = 'feminine' | 'masculine' | 'neutral';
interface Block { start: string; end: string; name: string }

const DAYS: { idx: string; label: string }[] = [
  { idx: '1', label: 'Monday' },
  { idx: '2', label: 'Tuesday' },
  { idx: '3', label: 'Wednesday' },
  { idx: '4', label: 'Thursday' },
  { idx: '5', label: 'Friday' },
  { idx: '6', label: 'Saturday' },
  { idx: '0', label: 'Sunday' },
];

const PROVIDERS: Record<string, { apiBase: string; model: string; label: string }> = {
  groq: { apiBase: 'https://api.groq.com/openai/v1', model: 'openai/gpt-oss-120b', label: 'Groq (free tier)' },
  openai: { apiBase: 'https://api.openai.com/v1', model: 'gpt-4o-mini', label: 'OpenAI' },
  xai: { apiBase: 'https://api.x.ai/v1', model: 'grok-4-fast', label: 'xAI (Grok)' },
  openrouter: { apiBase: 'https://openrouter.ai/api/v1', model: 'openai/gpt-4o-mini', label: 'OpenRouter' },
  custom: { apiBase: '', model: '', label: 'Custom (OpenAI-compatible)' },
};

const TIMEZONES = [
  'Asia/Karachi', 'Asia/Kolkata', 'Asia/Dhaka', 'Asia/Dubai', 'Asia/Singapore',
  'Europe/London', 'Europe/Berlin', 'America/New_York', 'America/Chicago',
  'America/Los_Angeles', 'Australia/Sydney', 'UTC',
];

const digits = (s: string) => s.replace(/\D/g, '');

function download(filename: string, content: string) {
  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

export default function Page() {
  // Identity
  const [botName, setBotName] = useState('Nova');
  const [botNumber, setBotNumber] = useState('');
  const [ownerNumber, setOwnerNumber] = useState('');
  const [timezone, setTimezone] = useState('Asia/Karachi');
  // AI
  const [provider, setProvider] = useState('groq');
  const [apiBase, setApiBase] = useState(PROVIDERS.groq.apiBase);
  const [model, setModel] = useState(PROVIDERS.groq.model);
  const [apiKey, setApiKey] = useState('');
  // Persona + memories
  const [gender, setGender] = useState<Gender>('neutral');
  const [voiceNotes, setVoiceNotes] = useState('');
  const [ownerNotes, setOwnerNotes] = useState('');
  // Timetable
  const workday: Block[] = [{ start: '09:00', end: '17:00', name: 'Work' }];
  const [timetable, setTimetable] = useState<Record<string, Block[]>>({
    '1': workday, '2': workday, '3': workday, '4': workday, '5': workday, '6': [], '0': [],
  });
  // Meetup
  const [meetupEnabled, setMeetupEnabled] = useState(false);
  const [askTime, setAskTime] = useState('10:00');
  const [cutoffTime, setCutoffTime] = useState('20:00');
  // Access
  const [groupJids, setGroupJids] = useState('');

  const setProviderPreset = (key: string) => {
    setProvider(key);
    if (key !== 'custom') {
      setApiBase(PROVIDERS[key].apiBase);
      setModel(PROVIDERS[key].model);
    }
  };

  const updateBlock = (day: string, i: number, patch: Partial<Block>) => {
    setTimetable((t) => ({
      ...t,
      [day]: t[day].map((b, j) => (j === i ? { ...b, ...patch } : b)),
    }));
  };
  const addBlock = (day: string) =>
    setTimetable((t) => ({ ...t, [day]: [...t[day], { start: '18:00', end: '19:00', name: '' }] }));
  const removeBlock = (day: string, i: number) =>
    setTimetable((t) => ({ ...t, [day]: t[day].filter((_, j) => j !== i) }));

  const config = useMemo(() => {
    const tt: Record<string, Block[]> = {};
    for (const { idx } of DAYS) {
      const blocks = (timetable[idx] || []).filter((b) => b.start && b.end);
      if (blocks.length) tt[idx] = blocks;
    }
    return {
      botName: botName.trim() || 'Nova',
      botNumber: digits(botNumber),
      ownerNumber: digits(ownerNumber),
      timezone: timezone.trim() || 'Asia/Karachi',
      llm: { enabled: true, model: model.trim(), apiBase: apiBase.trim() },
      persona: { gender, voiceNotes: voiceNotes.trim(), ownerNotes: ownerNotes.trim() },
      timetable: tt,
      meetup: { enabled: meetupEnabled, groupJid: '', askTime, cutoffTime },
      access: { groupJids: groupJids.split('\n').map((s) => s.trim()).filter(Boolean) },
    };
  }, [botName, botNumber, ownerNumber, timezone, model, apiBase, gender, voiceNotes, ownerNotes, timetable, meetupEnabled, askTime, cutoffTime, groupJids]);

  const configJs = useMemo(
    () => `// Generated by the Octopus Agent dashboard.\n// Drop this file in the project root (next to package.json), then run the agent.\nexport default ${JSON.stringify(config, null, 2)};\n`,
    [config],
  );

  const envFile = useMemo(
    () => [
      '# Your LLM API key — keep this file private, never commit it.',
      `LLM_API_KEY=${apiKey.trim()}`,
      `LLM_API_BASE=${apiBase.trim()}`,
      `LLM_MODEL=${model.trim()}`,
      `AGENT_TZ=${timezone.trim() || 'Asia/Karachi'}`,
      '',
    ].join('\n'),
    [apiKey, apiBase, model, timezone],
  );

  const [copied, setCopied] = useState('');
  const copy = async (label: string, text: string) => {
    try {
      await navigator.clipboard.writeText(text);
      setCopied(label);
      setTimeout(() => setCopied(''), 1600);
    } catch { /* clipboard unavailable */ }
  };

  return (
    <div className="wrap">
      <header className="hero">
        <div className="logo">🐙</div>
        <h1>Octopus Agent — Setup</h1>
        <p>Fill this in, download two files, drop them in the project. That&apos;s the whole setup.</p>
      </header>

      <section className="card">
        <h2>1 · Identity</h2>
        <p className="hint">The agent lives on a <b>spare WhatsApp number</b> (unofficial protocol — never your main number). Only the owner can DM it; everyone else can only reach it inside allowlisted groups.</p>
        <div className="grid">
          <label className="f"><span>Agent&apos;s name</span>
            <input type="text" value={botName} onChange={(e) => setBotName(e.target.value)} placeholder="Nova" />
          </label>
          <label className="f"><span>Timezone (IANA)</span>
            <input type="text" list="tzlist" value={timezone} onChange={(e) => setTimezone(e.target.value)} />
            <datalist id="tzlist">{TIMEZONES.map((z) => <option key={z} value={z} />)}</datalist>
          </label>
          <label className="f"><span>Agent&apos;s WhatsApp number (spare, with country code)</span>
            <input type="text" value={botNumber} onChange={(e) => setBotNumber(e.target.value)} placeholder="92xxxxxxxxxx" />
          </label>
          <label className="f"><span>Your number — the owner (with country code)</span>
            <input type="text" value={ownerNumber} onChange={(e) => setOwnerNumber(e.target.value)} placeholder="92xxxxxxxxxx" />
          </label>
        </div>
        {!ownerNumber && <div className="warn">⚠ Without an owner number, nobody can DM the agent — including you.</div>}
      </section>

      <section className="card">
        <h2>2 · AI brain</h2>
        <p className="hint">Any OpenAI-compatible chat API works. The key goes in the <code>.env</code> download — never into the config.</p>
        <div className="grid">
          <label className="f"><span>Provider</span>
            <select value={provider} onChange={(e) => setProviderPreset(e.target.value)}>
              {Object.entries(PROVIDERS).map(([k, v]) => <option key={k} value={k}>{v.label}</option>)}
            </select>
          </label>
          <label className="f"><span>Model</span>
            <input type="text" value={model} onChange={(e) => setModel(e.target.value)} />
          </label>
          <label className="f"><span>API base URL</span>
            <input type="text" value={apiBase} onChange={(e) => setApiBase(e.target.value)} />
          </label>
          <label className="f"><span>API key</span>
            <input type="text" value={apiKey} onChange={(e) => setApiKey(e.target.value)} placeholder="gsk_… / sk-…" autoComplete="off" />
          </label>
        </div>
      </section>

      <section className="card">
        <h2>3 · Personality &amp; memories</h2>
        <p className="hint">The agent already has a built-in texting style. Use these to make it yours: <b>voice notes</b> shape how it talks, <b>memories</b> are facts it should always know (about you, your people, your routines).</p>
        <div className="grid">
          <label className="f"><span>Persona gender (grammar for its own verbs)</span>
            <select value={gender} onChange={(e) => setGender(e.target.value as Gender)}>
              <option value="neutral">Neutral</option>
              <option value="feminine">Feminine</option>
              <option value="masculine">Masculine</option>
            </select>
          </label>
        </div>
        <label className="f"><span>Voice notes — how should it talk?</span>
          <textarea value={voiceNotes} onChange={(e) => setVoiceNotes(e.target.value)} placeholder="e.g. Extra blunt on Mondays. Never use emojis. Call the owner 'boss'." />
        </label>
        <label className="f"><span>Memories — what should it always know?</span>
          <textarea value={ownerNotes} onChange={(e) => setOwnerNotes(e.target.value)} placeholder="e.g. The owner is a student. Saturday football group meets at 6 PM. Mom's number is saved as 'Mom'." />
        </label>
      </section>

      <section className="card">
        <h2>4 · Weekly timetable</h2>
        <p className="hint">Your recurring busy blocks. The agent uses these to answer &ldquo;when is the owner free?&rdquo; and to suggest meetup times. Leave a day empty if nothing is fixed. Delete everything if you don&apos;t want schedule features at all.</p>
        {DAYS.map(({ idx, label }) => (
          <div className="day" key={idx}>
            <h3>{label}</h3>
            <button className="mini" onClick={() => addBlock(idx)}>+ Add block</button>
            {(timetable[idx] || []).map((b, i) => (
              <div className="blockrow" key={i}>
                <input type="time" value={b.start} onChange={(e) => updateBlock(idx, i, { start: e.target.value })} />
                <input type="time" value={b.end} onChange={(e) => updateBlock(idx, i, { end: e.target.value })} />
                <input type="text" value={b.name} onChange={(e) => updateBlock(idx, i, { name: e.target.value })} placeholder="What is it? (Work, Class, Gym…)" />
                <button className="mini danger" onClick={() => removeBlock(idx, i)}>✕</button>
              </div>
            ))}
          </div>
        ))}
      </section>

      <section className="card">
        <h2>5 · Meetup group (optional)</h2>
        <p className="hint">One group where the agent asks every day &ldquo;are we meeting today?&rdquo; and, if nobody confirms by the cutoff, posts a missed note with your longest free slot tomorrow. You pick the actual group later, inside WhatsApp: as the owner, say <code>{botName || 'Nova'} setup meetup here</code> in it.</p>
        <label className="check">
          <input type="checkbox" checked={meetupEnabled} onChange={(e) => setMeetupEnabled(e.target.checked)} />
          Enable the daily meetup flow
        </label>
        <div className="grid">
          <label className="f"><span>Ask at</span>
            <input type="time" value={askTime} onChange={(e) => setAskTime(e.target.value)} disabled={!meetupEnabled} />
          </label>
          <label className="f"><span>Cutoff at</span>
            <input type="time" value={cutoffTime} onChange={(e) => setCutoffTime(e.target.value)} disabled={!meetupEnabled} />
          </label>
        </div>
      </section>

      <section className="card">
        <h2>6 · Groups it may speak in</h2>
        <p className="hint">Group JIDs, one per line (they look like <code>120363…@g.us</code>). Don&apos;t know them yet? Leave this empty, start the agent, add it to a group and mention it — its console log shows the JID, and the meetup group above is always allowed. You can edit the config file later anytime.</p>
        <textarea value={groupJids} onChange={(e) => setGroupJids(e.target.value)} placeholder={'120363000000000000@g.us'} />
      </section>

      <section className="card">
        <h2>7 · Your files</h2>
        <p className="hint">Drop both files in the project root (next to <code>package.json</code>), then run <code>npm install</code>, <code>npm run build</code>, <code>npm start</code> and pair the spare phone.</p>
        <pre className="preview">{configJs}</pre>
        <div className="actions">
          <button className="big" onClick={() => download('config.js', configJs)}>⬇ Download config.js</button>
          <button className="big secondary" onClick={() => download('.env', envFile)}>⬇ Download .env</button>
          <button className="mini" onClick={() => copy('config', configJs)}>{copied === 'config' ? 'Copied ✓' : 'Copy config'}</button>
          <button className="mini" onClick={() => copy('env', envFile)}>{copied === 'env' ? 'Copied ✓' : 'Copy .env'}</button>
        </div>
        {!apiKey && <div className="warn">⚠ No API key yet — the .env will have an empty key. The agent runs but its brain stays off until you add one.</div>}
      </section>

      <section className="card">
        <h2>Then what?</h2>
        <ol className="steps">
          <li>On the spare phone: WhatsApp → Settings → Linked devices → Link a device — enter the pairing code the agent prints (or set <code>WA_PAIR=qr</code> and scan).</li>
          <li>DM the agent from your own number — it answers. Anyone else DMing it gets silence.</li>
          <li>Add it to your groups, mention it by name or @ — it joins the conversation.</li>
          <li>State (reminders, memory, the WhatsApp session) lives in <code>data/agent.db</code> + <code>data/auth/</code> — back those up, never share them.</li>
        </ol>
      </section>

      <footer>Octopus Agent template · MIT · Your data never leaves this page — everything here runs in your browser.</footer>
    </div>
  );
}
